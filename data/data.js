function getShowroomById(id) {

    return SHOWROOMS.find(showroom => showroom.id === id);

}


function getProduitById(id) {

    return PRODUITS.find(produit => produit.id === id);

}


function getProduitsByShowroom(showroom) {

    if (!showroom) {
        return [];
    }

    return showroom.equipements
        .map(id => getProduitById(id))
        .filter(produit => produit !== undefined);

}